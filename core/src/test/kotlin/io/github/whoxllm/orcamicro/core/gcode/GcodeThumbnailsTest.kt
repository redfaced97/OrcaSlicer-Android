package io.github.whoxllm.orcamicro.core.gcode

import java.nio.file.Files
import java.util.Base64
import kotlin.test.*

class GcodeThumbnailsTest {
    @Test fun `Orca thumbnail blocks decode exactly and leave commands and metadata unchanged`() {
        val directory=Files.createTempDirectory("gcode-preview").toFile()
        try {
            val file=directory.resolve("print.gcode")
            val original="; HEADER_BLOCK_START\r\n; generated by OrcaSlicer 2.4.2\r\n; estimated printing time (normal mode) = 1m 2s\r\n; HEADER_BLOCK_END\r\nG90\r\nM82\r\n;LAYER_CHANGE\r\n;Z:0.2\r\nG1 X10 Y10 Z0.2\r\nG1 X20 Y10 E1\r\nM104 S0\r\n"
            file.writeText(original)
            val png=byteArrayOf(-119,80,78,71,13,10,26,10)+ByteArray(400) { it.toByte() }
            GcodeThumbnails.embed(file,listOf(GcodeThumbnail(32,32,png),GcodeThumbnail(400,400,png)))
            val text=file.readText()
            assertTrue(text.startsWith(original.lineSequence().first()+"\r\n"))
            assertTrue(text.indexOf("; HEADER_BLOCK_END")<text.indexOf("; thumbnail begin"))
            val blocks=Regex("; THUMBNAIL_BLOCK_START\n.*?; THUMBNAIL_BLOCK_END\n\n",RegexOption.DOT_MATCHES_ALL)
            assertEquals(original,blocks.replace(text,""))
            assertEquals(2,blocks.findAll(text).count())
            for(block in blocks.findAll(text)) {
                val lines=block.value.lines()
                val index=lines.indexOfFirst { it.startsWith("; thumbnail begin ") }
                val count=lines[index].substringAfterLast(' ').toInt()
                val rows=lines.drop(index+1).takeWhile { it!="; thumbnail end" }
                assertTrue(rows.all { it.startsWith("; ") && it.length<=80 })
                val base64=rows.joinToString("") { it.removePrefix("; ") }
                assertEquals(count,base64.length)
                assertContentEquals(png,Base64.getDecoder().decode(base64))
            }
            val before=original.reader().buffered().use { GcodeParser.parse(it) }
            val after=file.bufferedReader().use { GcodeParser.parse(it) }
            assertEquals(before.stats,after.stats);assertEquals(before.layers.size,after.layers.size)
            assertContentEquals(before.layers.first().extrusions,after.layers.first().extrusions)
        } finally { directory.deleteRecursively() }
    }

    @Test fun `failed thumbnail insertion retains original G-code and removes temporary file`() {
        val directory=Files.createTempDirectory("gcode-preview").toFile()
        try {
            val file=directory.resolve("print.gcode");val original=";".repeat(17000)
            file.writeText(original)
            val png=byteArrayOf(-119,80,78,71,13,10,26,10)
            assertFailsWith<IllegalArgumentException> { GcodeThumbnails.embed(file,listOf(GcodeThumbnail(32,32,png))) }
            assertEquals(original,file.readText());assertFalse(directory.resolve("print.gcode.thumbnail.tmp").exists())
        } finally { directory.deleteRecursively() }
    }
}
